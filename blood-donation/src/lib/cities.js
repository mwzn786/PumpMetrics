const CITY_SET = new Set(PAKISTAN_CITIES);

export function isPakistanCity(value) {
  return CITY_SET.has(String(value ?? "").trim());
}

export function filterCities(query, limit = 12) {
  const needle = String(query ?? "").trim().toLowerCase();
  if (!needle) return PAKISTAN_CITIES.slice(0, limit);
  return PAKISTAN_CITIES.filter((city) => city.toLowerCase().includes(needle)).slice(
    0,
    limit,
  );
}
